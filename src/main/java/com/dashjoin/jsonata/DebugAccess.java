package com.dashjoin.jsonata;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

import com.dashjoin.jsonata.Jsonata.Frame;
import com.dashjoin.jsonata.Jsonata.JFunction;
import com.dashjoin.jsonata.Jsonata.JLambda;
import com.dashjoin.jsonata.Parser.Symbol;

/**
 * debug-api: read-only bridge to engine internals needed by {@code com.dashjoin.jsonata.debug}.
 * Keeps the AST ({@link Symbol}) fields package-private while giving the debugger
 * a structural view of the processed AST.
 */
public final class DebugAccess {

    private DebugAccess() {}

    /** a named child edge of the processed AST */
    public static final class Child {
        public final String role;
        public final Symbol node;
        Child(String role, Symbol node) { this.role = role; this.node = node; }
    }

    /**
     * Children of a processed AST node, in evaluation-relevant order.
     * Covers: path steps, stages/predicates (filter, index), group-by pairs, sort terms,
     * binary/bind/apply operands, unary operand / array items / object pairs,
     * function/partial procedure and arguments, lambda parameters and body,
     * condition, transform, block expressions.
     */
    public static List<Child> children(Symbol s) {
        if (s == null) return Collections.emptyList();
        List<Child> c = new ArrayList<>();
        add(c, "procedure", s.procedure);
        if (s.steps != null) for (Symbol x : s.steps) add(c, "step", x);
        if (s.lhs != null) add(c, "lhs", s.lhs);
        if (s.rhs != null) add(c, "rhs", s.rhs);
        if (s.expression != null) add(c, "expression", s.expression);
        if (s.expressions != null) for (Symbol x : s.expressions) add(c, "item", x);
        if (s.lhsObject != null) for (Symbol[] p : s.lhsObject) { add(c, "key", p[0]); add(c, "value", p[1]); }
        if (s.terms != null) for (Symbol t : s.terms) add(c, t.descending ? "sortTermDesc" : "sortTerm", t.expression);
        if (s.arguments != null) for (Symbol x : s.arguments) add(c, isLambda(s) ? "param" : "argument", x);
        if (s.body != null) add(c, "body", s.body);
        if (s.condition != null) add(c, "condition", s.condition);
        if (s.then != null) add(c, "then", s.then);
        if (s._else != null) add(c, "else", s._else);
        if (s.pattern != null) add(c, "pattern", s.pattern);
        if (s.update != null) add(c, "update", s.update);
        if (s.delete != null) add(c, "delete", s.delete);
        if (s.expr instanceof Symbol) add(c, "predicate", (Symbol) s.expr);
        if (s.stages != null) for (Symbol x : s.stages) add(c, "stage", x);
        if (s.predicate != null) for (Symbol x : s.predicate) add(c, "filter", x);
        if (s.group != null) add(c, "group", s.group);
        return c;
    }

    private static void add(List<Child> c, String role, Symbol s) {
        if (s != null) c.add(new Child(role, s));
    }

    /** node kind: the jsonata-js AST 'type' ('group' for a group-by clause node) */
    public static String kind(Symbol s) {
        if (s.type == null) return s.lhsObject != null ? "group" : "?";
        return s.type;
    }

    public static boolean isLambda(Symbol s) { return "lambda".equals(s.type); }
    /** synthetic lambda generated by tail-call optimisation (body = the tail call) */
    public static boolean isThunk(Symbol s) { return s.thunk; }
    public static Symbol lambdaBody(Symbol s) { return s.body; }
    public static List<Symbol> lambdaParams(Symbol s) { return s.arguments; }
    public static Symbol procedureOf(Symbol call) { return call.procedure; }
    /** focus variable name of a path step ({@code @$v}) or null */
    public static Object focusVariable(Symbol step) { return step.focus; }
    /** index variable name of a path step ({@code #$i}) or null */
    public static Object indexVariable(Symbol step) { return step.index; }
    /** true if this step/path is evaluated as a tuple stream */
    public static boolean isTupleStep(Symbol s) { return s.tuple instanceof Boolean && (Boolean) s.tuple; }
    /** runtime lambda value (closure): user-defined function? */
    public static boolean isLambdaValue(Object v) { return v instanceof Symbol && ((Symbol) v)._jsonata_lambda; }
    /** AST body of a runtime lambda value */
    public static Symbol lambdaValueBody(Object v) { return v instanceof Symbol ? ((Symbol) v).body : null; }

    /**
     * Evaluates a (parsed) expression in the scope of a suspended evaluation:
     * {@code $} = context, all variables visible in {@code scope} (incl. {@code $$}) are visible.
     * Runs without debugger notifications and restores the per-thread engine state.
     */
    public static Object evaluateInScope(Jsonata expr, Object context, Frame scope) {
        Jsonata saved = Jsonata.current.get();
        try {
            Frame f = new Frame(scope);
            f.base = f;                      // own base: no debug hook, own depth/time accounting
            f.time = System.currentTimeMillis();
            f.options = scope != null && scope.base != null ? scope.base.options : null;
            Object r = expr.evaluate(expr.ast, context, f);
            return Utils.convertNulls(r);
        } finally {
            Jsonata.current.set(saved);
        }
    }

    /** parses an expression without disturbing the per-thread engine state */
    public static Jsonata parse(String expression) {
        Jsonata saved = Jsonata.current.get();
        try {
            return Jsonata.jsonata(expression);
        } finally {
            Jsonata.current.set(saved);
        }
    }

    /** the value of {@code $} for a node evaluated with the given input (unwraps the outer array wrapper) */
    public static Object contextValue(Object input) {
        if (input instanceof Utils.JList && ((Utils.JList<?>) input).outerWrapper) return ((Utils.JList<?>) input).get(0);
        return input;
    }

    /** JSONata truthiness (as used by predicates / conditions) */
    public static boolean truthy(Object v) {
        Boolean b = Functions.toBoolean(v);
        return b != null && b;
    }

    /** JSON rendering of a value for display (functions are shown as their kind) */
    public static String render(Object v) {
        if (v == null) return "undefined";
        if (isLambdaValue(v)) return "<lambda>";
        if (v instanceof JFunction || v instanceof JLambda) return "<native function>";
        try {
            return Functions.string(v, false);
        } catch (RuntimeException e) {
            return String.valueOf(v);
        }
    }
}
